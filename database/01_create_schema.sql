CREATE TABLE PAYMENT (
 id NUMBER PRIMARY KEY, external_ref VARCHAR2(40) UNIQUE NOT NULL, status VARCHAR2(20) NOT NULL,
 amount NUMBER(18,2) NOT NULL, updated_at TIMESTAMP NOT NULL, row_version NUMBER DEFAULT 0 NOT NULL,
 CONSTRAINT CK_PAYMENT_STATUS CHECK(status IN ('PENDING','CONFIRMED','REJECTED')),
 CONSTRAINT CK_PAYMENT_AMOUNT CHECK(amount>0)
);
CREATE TABLE PROVIDER_EVENT (
 id NUMBER PRIMARY KEY, payment_id NUMBER NOT NULL, provider_event_id VARCHAR2(60) UNIQUE NOT NULL,
 provider_status VARCHAR2(20) NOT NULL, received_at TIMESTAMP NOT NULL,
 CONSTRAINT FK_EVENT_PAYMENT FOREIGN KEY(payment_id) REFERENCES PAYMENT(id),
 CONSTRAINT CK_PROVIDER_STATUS CHECK(provider_status IN ('APPROVED','DECLINED'))
);
CREATE TABLE LEDGER_ENTRY (
 id NUMBER PRIMARY KEY, payment_id NUMBER NOT NULL, entry_type VARCHAR2(20) NOT NULL,
 amount NUMBER(18,2) NOT NULL, related_entry_id NUMBER NULL, created_at TIMESTAMP NOT NULL,
 CONSTRAINT FK_LEDGER_PAYMENT FOREIGN KEY(payment_id) REFERENCES PAYMENT(id),
 CONSTRAINT FK_LEDGER_RELATED FOREIGN KEY(related_entry_id) REFERENCES LEDGER_ENTRY(id),
 CONSTRAINT CK_LEDGER_TYPE CHECK(entry_type IN ('DEBIT','REVERSAL')),
 CONSTRAINT CK_LEDGER_AMOUNT CHECK(amount>0),
 CONSTRAINT CK_LEDGER_RELATION CHECK((entry_type='DEBIT' AND related_entry_id IS NULL) OR (entry_type='REVERSAL' AND related_entry_id IS NOT NULL))
);
CREATE TABLE SUPPORT_AUDIT (
 id NUMBER PRIMARY KEY, payment_id NUMBER NOT NULL, action VARCHAR2(40) NOT NULL,
 reason VARCHAR2(400) NOT NULL, created_at TIMESTAMP NOT NULL,
 CONSTRAINT FK_AUDIT_PAYMENT FOREIGN KEY(payment_id) REFERENCES PAYMENT(id)
);
